// Package storage keeps uploaded files. Today files live on local disk (the
// uploads volume); an S3-compatible implementation can replace it without
// touching the modules that use the Store interface.
package storage

import (
	"errors"
	"fmt"
	"io"
	"os"
	"path/filepath"
	"regexp"
)

// ErrNotFound is returned when a key does not exist.
var ErrNotFound = errors.New("file not found")

// Store saves, opens and deletes files by key.
type Store interface {
	Save(key string, r io.Reader) (written int64, err error)
	Open(key string) (io.ReadCloser, error)
	Delete(key string) error
}

// keyPattern: keys are generated by the server (UUID-based paths), never
// taken from users, but are validated anyway to rule out path traversal.
var keyPattern = regexp.MustCompile(`^[a-z0-9-]+(/[a-z0-9-]+)*$`)

// Local stores files under a root directory.
type Local struct{ root string }

// NewLocal creates the root directory if needed.
func NewLocal(root string) (*Local, error) {
	if err := os.MkdirAll(root, 0o750); err != nil {
		return nil, fmt.Errorf("storage: create %s: %w", root, err)
	}
	return &Local{root: root}, nil
}

func (l *Local) path(key string) (string, error) {
	if !keyPattern.MatchString(key) {
		return "", fmt.Errorf("storage: invalid key %q", key)
	}
	return filepath.Join(l.root, filepath.FromSlash(key)), nil
}

// Save writes r to key atomically (temp file + rename).
func (l *Local) Save(key string, r io.Reader) (int64, error) {
	p, err := l.path(key)
	if err != nil {
		return 0, err
	}
	if err := os.MkdirAll(filepath.Dir(p), 0o750); err != nil {
		return 0, err
	}
	tmp, err := os.CreateTemp(filepath.Dir(p), ".upload-*")
	if err != nil {
		return 0, err
	}
	n, err := io.Copy(tmp, r)
	if cerr := tmp.Close(); err == nil {
		err = cerr
	}
	if err != nil {
		_ = os.Remove(tmp.Name())
		return 0, err
	}
	return n, os.Rename(tmp.Name(), p)
}

// Open returns the file for reading.
func (l *Local) Open(key string) (io.ReadCloser, error) {
	p, err := l.path(key)
	if err != nil {
		return nil, err
	}
	f, err := os.Open(p)
	if errors.Is(err, os.ErrNotExist) {
		return nil, ErrNotFound
	}
	return f, err
}

// Delete removes the file (missing files are not an error).
func (l *Local) Delete(key string) error {
	p, err := l.path(key)
	if err != nil {
		return err
	}
	if err := os.Remove(p); err != nil && !errors.Is(err, os.ErrNotExist) {
		return err
	}
	return nil
}
